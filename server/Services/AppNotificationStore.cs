using Microsoft.EntityFrameworkCore;
using StoreMaster.Server.Data;
using System.Threading;

namespace StoreMaster.Server.Services;

/// <summary>
/// PostgreSQL-backed persistent in-app notifications. DDL is intentionally
/// idempotent so existing installations can upgrade without an EF migration.
/// </summary>
public static class AppNotificationStore
{
    // Client dashboards poll every ~10 seconds. Never run ALTER/CREATE statements
    // on every poll: initialize once at startup or on the first call instead.
    private static readonly SemaphoreSlim SchemaLock = new(1, 1);
    private static volatile bool _schemaReady;

    public static async Task EnsureSchemaAsync(StoreMasterDbContext db, CancellationToken ct = default)
    {
        if (_schemaReady) return;
        await SchemaLock.WaitAsync(ct);
        try
        {
            if (_schemaReady) return;
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "AppNotifications" (
                    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "StoreId" integer NULL,
                    "EventType" text NOT NULL DEFAULT 'info',
                    "Title" text NOT NULL DEFAULT '',
                    "Message" text NOT NULL DEFAULT '',
                    "MetadataJson" text NOT NULL DEFAULT '{}',
                    "DeduplicationKey" text NULL,
                    "CreatedAt" timestamptz NOT NULL DEFAULT now()
                );
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "StoreId" integer NULL;
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "EventType" text NOT NULL DEFAULT 'info';
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "Title" text NOT NULL DEFAULT '';
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "Message" text NOT NULL DEFAULT '';
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "MetadataJson" text NOT NULL DEFAULT '{}';
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "DeduplicationKey" text NULL;
                ALTER TABLE "AppNotifications" ADD COLUMN IF NOT EXISTS "CreatedAt" timestamptz NOT NULL DEFAULT now();
                CREATE INDEX IF NOT EXISTS "IX_AppNotifications_StoreId_Id" ON "AppNotifications" ("StoreId", "Id");
                CREATE UNIQUE INDEX IF NOT EXISTS "IX_AppNotifications_DeduplicationKey" ON "AppNotifications" ("DeduplicationKey");
                CREATE TABLE IF NOT EXISTS "AppNotificationReceipts" (
                    "NotificationId" bigint NOT NULL,
                    "UserId" integer NOT NULL,
                    "ReadAt" timestamptz NOT NULL DEFAULT now(),
                    PRIMARY KEY ("NotificationId", "UserId")
                );
                CREATE INDEX IF NOT EXISTS "IX_AppNotificationReceipts_UserId_NotificationId" ON "AppNotificationReceipts" ("UserId", "NotificationId");
                """, cancellationToken: ct);
            _schemaReady = true;
        }
        finally
        {
            SchemaLock.Release();
        }
    }

    public static async Task PublishAsync(
        StoreMasterDbContext db,
        int? storeId,
        string eventType,
        string title,
        string message,
        string metadataJson = "{}",
        string? deduplicationKey = null,
        CancellationToken ct = default)
    {
        await EnsureSchemaAsync(db, ct);
        await db.Database.ExecuteSqlInterpolatedAsync($"""
            INSERT INTO "AppNotifications"
                ("StoreId", "EventType", "Title", "Message", "MetadataJson", "DeduplicationKey", "CreatedAt")
            VALUES
                ({storeId}, {Clip(eventType, 60)}, {Clip(title, 180)}, {Clip(message, 3000)}, {Clip(metadataJson, 12000)}, {deduplicationKey}, now())
            ON CONFLICT ("DeduplicationKey") DO NOTHING
            """, ct);
    }

    public static async Task<int?> FindStoreIdAsync(StoreMasterDbContext db, string? storeCode, string? licenseId = null, CancellationToken ct = default)
    {
        var candidates = new[] { storeCode?.Trim(), licenseId?.Trim() }
            .Where(x => !string.IsNullOrWhiteSpace(x)).Distinct().ToArray();
        if (candidates.Length == 0) return null;
        return await db.Stores.AsNoTracking()
            .Where(s => candidates.Contains(s.Code))
            .Select(s => (int?)s.Id)
            .FirstOrDefaultAsync(ct);
    }

    private static string Clip(string? value, int max)
    {
        var s = (value ?? string.Empty).Trim();
        return s.Length <= max ? s : s[..max];
    }
}
