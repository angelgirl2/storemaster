CREATE TABLE IF NOT EXISTS stores (
  id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'RETAIL', business_title TEXT NOT NULL DEFAULT '', currency TEXT NOT NULL DEFAULT 'IRR',
  active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT NOT NULL, name TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  pin_hash TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_users_username ON users(username);
CREATE TABLE IF NOT EXISTS store_users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER NOT NULL REFERENCES stores(id), user_id INTEGER NOT NULL REFERENCES users(id),
  role TEXT NOT NULL DEFAULT 'SELLER', permissions_json TEXT NOT NULL DEFAULT '[]', active INTEGER NOT NULL DEFAULT 1,
  UNIQUE(store_id,user_id)
);
CREATE TABLE IF NOT EXISTS user_devices (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER NOT NULL, user_id INTEGER NOT NULL, device_id TEXT NOT NULL,
  platform TEXT NOT NULL DEFAULT '', name TEXT NOT NULL DEFAULT '', first_seen_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, active INTEGER NOT NULL DEFAULT 1, UNIQUE(store_id,user_id,device_id)
);
CREATE TABLE IF NOT EXISTS licenses (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER NOT NULL REFERENCES stores(id), license_id TEXT NOT NULL UNIQUE,
  activation_code TEXT NOT NULL UNIQUE, activation_code_used INTEGER NOT NULL DEFAULT 0, plan TEXT NOT NULL DEFAULT 'TRIAL', status TEXT NOT NULL DEFAULT 'ACTIVE',
  issued_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, expires_at TEXT NOT NULL, original_price REAL NOT NULL DEFAULT 0,
  final_price REAL NOT NULL DEFAULT 0, discount_code TEXT NOT NULL DEFAULT '', features_json TEXT NOT NULL DEFAULT '[]',
  business_types_json TEXT NOT NULL DEFAULT '["*"]', max_users INTEGER NOT NULL DEFAULT 5, username TEXT NOT NULL DEFAULT 'admin',
  initial_password TEXT NOT NULL DEFAULT '', recovery_code TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_licenses_store ON licenses(store_id,expires_at);
CREATE TABLE IF NOT EXISTS sync_changes (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER NOT NULL, user_id INTEGER NOT NULL, entity TEXT NOT NULL,
  operation TEXT NOT NULL DEFAULT 'UPSERT', entity_id TEXT NOT NULL, payload_json TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_sync_changes_store_id ON sync_changes(store_id,id);
CREATE TABLE IF NOT EXISTS cloud_records (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER NOT NULL, user_id INTEGER NOT NULL, entity TEXT NOT NULL, entity_id TEXT NOT NULL,
  operation TEXT NOT NULL DEFAULT 'UPSERT', payload_json TEXT NOT NULL DEFAULT '{}', source_version INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(store_id,entity,entity_id)
);
CREATE TABLE IF NOT EXISTS trial_policy (
  id INTEGER PRIMARY KEY CHECK(id=1), features_json TEXT NOT NULL DEFAULT '["sales","products","customers"]',
  business_types_json TEXT NOT NULL DEFAULT '["*"]', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT OR IGNORE INTO trial_policy(id) VALUES(1);
CREATE TABLE IF NOT EXISTS discounts (
  id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT NOT NULL UNIQUE, percent INTEGER NOT NULL DEFAULT 0, fixed_amount REAL NOT NULL DEFAULT 0,
  max_uses INTEGER NOT NULL DEFAULT 0, used_count INTEGER NOT NULL DEFAULT 0, expires_at TEXT, active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS pricing_entries (
  id INTEGER PRIMARY KEY AUTOINCREMENT, plan_days INTEGER NOT NULL UNIQUE, price REAL NOT NULL, currency TEXT NOT NULL DEFAULT 'تومان', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS support_tickets (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ticket_code TEXT NOT NULL UNIQUE, type TEXT NOT NULL DEFAULT 'SUPPORT', store_code TEXT NOT NULL DEFAULT '',
  license_id TEXT NOT NULL DEFAULT '', username TEXT NOT NULL DEFAULT 'admin', device_id TEXT NOT NULL DEFAULT '', contact TEXT NOT NULL DEFAULT '',
  message TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'OPEN', access_token_hash TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS support_messages (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ticket_id INTEGER NOT NULL REFERENCES support_tickets(id), sender_role TEXT NOT NULL DEFAULT 'CUSTOMER',
  sender_name TEXT NOT NULL DEFAULT 'کاربر', message TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_support_messages_ticket ON support_messages(ticket_id,id);
CREATE TABLE IF NOT EXISTS invoice_shares (
  id INTEGER PRIMARY KEY AUTOINCREMENT, token TEXT NOT NULL UNIQUE, store_id INTEGER NOT NULL, store_name TEXT NOT NULL DEFAULT '',
  store_phone TEXT NOT NULL DEFAULT '', invoice_number TEXT NOT NULL DEFAULT '', date_text TEXT NOT NULL DEFAULT '', customer_name TEXT NOT NULL DEFAULT '',
  currency TEXT NOT NULL DEFAULT 'تومان', items_json TEXT NOT NULL DEFAULT '[]', total_amount REAL NOT NULL DEFAULT 0, discount REAL NOT NULL DEFAULT 0,
  final_amount REAL NOT NULL DEFAULT 0, paid_amount REAL NOT NULL DEFAULT 0, debt_amount REAL NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER PRIMARY KEY AUTOINCREMENT, store_id INTEGER, event_type TEXT NOT NULL, title TEXT NOT NULL, message TEXT NOT NULL,
  metadata_json TEXT NOT NULL DEFAULT '{}', dedupe_key TEXT UNIQUE, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_notifications_store ON notifications(store_id,id);
CREATE TABLE IF NOT EXISTS notification_receipts (
  notification_id INTEGER NOT NULL REFERENCES notifications(id), user_id INTEGER NOT NULL, read_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(notification_id,user_id)
);
CREATE TABLE IF NOT EXISTS login_rate_limits (
  rate_key TEXT PRIMARY KEY, count INTEGER NOT NULL DEFAULT 0,
  window_started_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, blocked_until TEXT
);
